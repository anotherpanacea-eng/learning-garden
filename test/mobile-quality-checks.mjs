import assert from 'node:assert/strict';
import {chooseLocalVoice,localVoices,setSpeechPreferences,speechPreferences,resetSpeechPreferences} from '../dist/play-media.mjs';

let checks=0;
const equal=(actual,expected,message)=>{assert.equal(actual,expected,message);checks++;};
const basic={name:'Synthetic basic',voiceURI:'basic-en',lang:'en-US',localService:true,default:true};
const preferred={name:'Synthetic enhanced',voiceURI:'enhanced-en',lang:'en-GB',localService:true};
const french={name:'Synthetic français',voiceURI:'local-fr',lang:'fr-FR',localService:true};
const remote={name:'Synthetic remote premium',voiceURI:'remote-en',lang:'en-US',localService:false};
const voices=[basic,preferred,french,remote];

equal(chooseLocalVoice(voices,'basic-en'),basic,'explicit choice wins over quality-name heuristic');
equal(chooseLocalVoice(voices,'enhanced-en'),preferred,'selected object is passed through unchanged');
equal(chooseLocalVoice([...voices].reverse(),'enhanced-en'),preferred,'enumeration order cannot change an explicit voice');
equal(chooseLocalVoice(voices,'removed-en'),null,'a missing saved choice never silently substitutes');
equal(chooseLocalVoice(voices,'remote-en'),null,'a saved remote choice cannot substitute a local voice');
equal(chooseLocalVoice([],'enhanced-en'),null,'delayed enumeration keeps a saved choice unavailable');
equal(chooseLocalVoice(voices,'enhanced-en'),preferred,'the same key resolves after voices arrive');
equal(chooseLocalVoice([basic],'enhanced-en'),null,'removing the chosen voice does not pick the default');
equal(chooseLocalVoice(voices),preferred,'automatic selection retains the established local heuristic');
equal(chooseLocalVoice([remote]),null,'automatic never uses a remote voice');
equal(chooseLocalVoice([basic,remote],'','fr'),null,'language matching never uses an English voice for French');
equal(chooseLocalVoice(voices,'local-fr','fr'),french,'explicit French voice is selected');
equal(chooseLocalVoice(voices,'basic-en','fr'),french,'a known English preference leaves French on automatic local selection');
equal(chooseLocalVoice(voices,'local-fr','en'),preferred,'a known French preference leaves English on automatic local selection');
equal(chooseLocalVoice(voices,'missing-fr','fr'),null,'an absent French choice cannot silently substitute');
equal(localVoices(voices,'fr').length,1,'local French list excludes English and remote services');
const sameName={...preferred,voiceURI:'other-uri'};
equal(chooseLocalVoice([sameName,preferred],'enhanced-en'),preferred,'same name does not override URI identity');
const withoutUri={name:'Synthetic fallback key',lang:'en_US',localService:true};
equal(chooseLocalVoice([withoutUri],'Synthetic fallback key|en_US'),withoutUri,'name/language identity works when URI is absent');

let cancellations=0;
globalThis.window={speechSynthesis:{cancel(){cancellations++;}}};
setSpeechPreferences({voice:'enhanced-en',rate:0.8});
equal(speechPreferences().voice,'enhanced-en','saved preference loads unchanged');
equal(speechPreferences().rate,0.8,'saved supported speed loads');
chooseLocalVoice([],'enhanced-en');
equal(speechPreferences().voice,'enhanced-en','empty enumeration never overwrites preference');
setSpeechPreferences({voice:'basic-en',rate:1.15});
equal(speechPreferences().voice,'basic-en','switching explorers loads the other preference');
setSpeechPreferences({voice:'enhanced-en',rate:0.8});
equal(speechPreferences().voice,'enhanced-en','switching back restores the original preference');
setSpeechPreferences({voice:42,rate:5});
equal(speechPreferences().voice,'','malformed preference returns to automatic');
equal(speechPreferences().rate,1,'malformed speed returns to natural pace');
resetSpeechPreferences();
equal(speechPreferences().voice,'','reset clears voice');
equal(speechPreferences().rate,1,'reset clears speed');
equal(cancellations,5,'preference changes and reset cancel queued speech');
delete globalThis.window;
console.log(`${checks} mobile narration selection and preference checks passed.`);
