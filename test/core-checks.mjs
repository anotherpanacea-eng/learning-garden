import assert from 'node:assert/strict';
import {freshState,observation,recommendations,makePractice,factKey,numericAnswer,describe,restoreState} from '../dist/core.mjs';
import {checkin,puzzles} from '../dist/content.mjs';
let checks=0;function check(v,message){assert.ok(v,message);checks++;}
const active=(attempts,other={})=>({attempts,hinted:false,revealed:false,...other});
const q=checkin[2];
check(observation(q,active([24]),'worked').independent,'Derived first answers remain independent');
check(!observation(q,active([24],{hinted:true}),'knew').independent,'Hint is not erased by knew method');
check(!observation(q,active([24],{revealed:true}),'knew').independent,'Solution cannot count independent');
check(!observation(q,active([23,24]),'knew').independent,'A retry is not first-pass independence');
check(describe(observation(q,active([23,24]),'knew'))==='Found it after another try','Retry description truthful');
check(observation(q,active([]),'together',true).status==='skipped','Skip is unassessed');
check(observation(q,active([23]),'together',true).status==='explored','Wrong then leave retains attempted evidence');
check(numericAnswer('')===null && numericAnswer('24abc')===null && numericAnswer('24')===24 && numericAnswer(' 0 ')===0,'Strict numeric evaluation');
let s=freshState();check(recommendations(s).route==='mixed','Absent baseline neutral');
s.baseline.observations=checkin.map(x=>observation(x,active([]),'together',true));check(recommendations(s).route==='mixed','All skips neutral');
s.baseline.observations=[observation(checkin[0],active([11]),'together',true)];check(recommendations(s).route==='visual','Unresolved groups suggest pictures');
s=freshState();s.baseline.observations=[observation(checkin[0],active([12]),'worked'),observation(q,active([23]),'together',true)];
const p=makePractice(s);check(p.some(x=>factKey(...x.fact)==='4x6'),'Unresolved fact is actually selected');
check(p.length===6 && new Set(p.map(x=>factKey(...x.fact))).size===6,'Six distinct practice tasks');
for(const x of p)check(x.answer===x.a*x.b,'Generated fact correct');
s=freshState();const first=makePractice(s);s.practice=first.map((x,i)=>observation(x,active([i===5?x.answer+1:x.answer]),'knew'));
s.sessions=1;const next=makePractice(s);check(factKey(...next[0].fact)!==factKey(...first[5].fact),'No immediate exact/commuted repeat across sets');
check(next.some(x=>factKey(...x.fact)===factKey(...first[5].fact)),'Unresolved fact still appears later');
check(makePractice(freshState(),'strategy').every(x=>x.strategyLead),'Strategy path contains explicit instruction');
check(makePractice(freshState(),'visual').every(x=>x.visual),'Visual path shows groups');
check(restoreState('bad').baseline.index===0,'Malformed state recovers');
const bad=freshState();bad.baseline.draft={questionId:'groups',attempts:'oops'};check(!restoreState(JSON.stringify(bad)).baseline.draft,'Malformed draft discarded');
check(JSON.stringify(checkin.map(x=>x.answer))==='[12,1,24,56,3,22]','Reviewed check-in keys');
check(JSON.stringify(puzzles.map(x=>x.answer))==='[12,15,12,6,20,42]','Reviewed puzzle keys');
console.log(`${checks} focused checks passed.`);
