import assert from 'node:assert/strict';
import {evidenceCards} from '../dist/water-evidence-content.mjs';
import {evidenceShelfPage,evidenceShelfState,startEvidenceShelf,evidenceShelfAction,resetEvidenceShelf} from '../dist/water-evidence-ui.mjs';
import {freshState} from '../dist/core.mjs';
import {initializeExplorerState} from '../dist/progress-transfer.mjs';

const state=initializeExplorerState(freshState()),before=JSON.stringify(state);
assert.deepEqual(evidenceCards.map(c=>c.fit),[0,1,2]);
assert.deepEqual(evidenceCards.map(c=>c.options.length),[3,3,3]);
assert.deepEqual(evidenceCards.map(c=>c.id),['puddle','soil','dish']);
assert.match(evidenceCards[0].feedback,/flow.*soak.*evaporate/i);
assert.match(evidenceCards[1].feedback,/cannot establish depth, amount, or exclude flow and evaporation/);
assert.match(evidenceCards[2].scene,/Nobody pours or spills.*no drain/);
assert.match(evidenceCards[2].feedback,/vapor is not directly seen.*neither a measurement nor proof/);
assert.match(evidenceShelfPage('explorer-1'),/Three made-up before-and-after pictures/);
assert.equal(evidenceShelfState('explorer-1'),null);
assert.equal(startEvidenceShelf('explorer-1'),true);
assert.equal(evidenceShelfAction('explorer-1','choice',1),true);
assert.equal(evidenceShelfAction('explorer-1','note'),true);
assert.equal(evidenceShelfAction('explorer-1','clue'),true);
assert.match(evidenceShelfPage('explorer-1'),/The picture cannot single out evaporation/);
assert.equal(evidenceShelfAction('explorer-1','page',1),true);
assert.equal(evidenceShelfAction('explorer-1','choice',1),true);
assert.equal(evidenceShelfAction('explorer-1','page',0),true);
assert.equal(evidenceShelfState('explorer-1').choices[0],1);
assert.equal(evidenceShelfState('explorer-1').revealed[0],true);
assert.equal(evidenceShelfState('explorer-1').clues[0],true);
assert.equal(evidenceShelfState('explorer-2'),null);
assert.doesNotMatch(evidenceShelfPage('explorer-2'),/data-evidence-card=/);
assert.equal(evidenceShelfAction('explorer-2','choice',0),false);
assert.equal(evidenceShelfAction('explorer-1','page',4),false);
resetEvidenceShelf();
assert.equal(evidenceShelfState('explorer-1'),null);
assert.doesNotMatch(evidenceShelfPage('explorer-1'),/data-evidence-card=/);
assert.equal(JSON.stringify(state),before,'the shelf creates no saved activity data');
console.log('Water Evidence Shelf source and transient-session checks passed.');

startEvidenceShelf('synthetic-surface');evidenceShelfAction('synthetic-surface','page',1);assert.ok(evidenceShelfPage('synthetic-surface').includes('Soil surface, seen from above'),'soil picture explicitly uses a surface view');resetEvidenceShelf();
